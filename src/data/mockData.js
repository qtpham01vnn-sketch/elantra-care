const getRelativeDate = (monthsOffset, daysOffset = 0) => {
  const d = new Date();
  d.setMonth(d.getMonth() + monthsOffset);
  d.setDate(d.getDate() + daysOffset);
  return d.toISOString().split('T')[0];
};

